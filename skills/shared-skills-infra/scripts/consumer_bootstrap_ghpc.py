REQUIRED_PIN_KEYS = {
    "main_commit", "owned_tree_path", "owned_tree",
    "candidate_commit", "candidate_source_path", "candidate_repin_policy",
}


def ghpc_profile_document(path: Path) -> dict[str, Any]:
    value = read_json(path)
    if value.get("schema") != PROFILE_SCHEMA:
        raise BootstrapError("unsupported control-plane profile")
    if value.get("profile") != PROFILE_ID:
        raise BootstrapError(f"profile is not the {PROFILE_ID} profile")
    skills = value.get("skills")
    if not isinstance(skills, list) or not skills or any(not isinstance(s, str) or not s for s in skills):
        raise BootstrapError("control-plane profile Skill closure is invalid")
    authority = value.get("authority")
    if not isinstance(authority, dict) or not authority or any(v is not False for v in authority.values()):
        raise BootstrapError("control-plane profile widened automatic authority")
    pin = value.get("subject_pin")
    if not isinstance(pin, dict) or set(pin) != REQUIRED_PIN_KEYS:
        raise BootstrapError("control-plane profile is missing its subject pin")
    for key in ("main_commit", "owned_tree", "candidate_commit"):
        if not HEX40.fullmatch(pin[key]):
            raise BootstrapError(f"control-plane profile subject pin {key} is not an exact commit/tree SHA")
    return value


def validate_subject_pin(shared_root: Path, pin: dict[str, str]) -> tuple[str, str]:
    """Prove the profile's declared subject pin is neither stale nor
    substituted, and return the running checkout's own (commit, tree)."""
    if git_out(shared_root, "status", "--porcelain", "--untracked-files=all"):
        raise BootstrapError("skills-shared source must be clean")
    head_commit = git_out(shared_root, "rev-parse", "HEAD")
    head_tree = git_out(shared_root, "rev-parse", "HEAD^{tree}")
    if not HEX40.fullmatch(head_commit) or not HEX40.fullmatch(head_tree):
        raise BootstrapError("invalid skills-shared commit/tree")

    main_commit = pin["main_commit"]
    if run_git(shared_root, "cat-file", "-e", main_commit, check=False).returncode:
        raise BootstrapError("pinned main_commit is absent from this checkout's object database")
    if run_git(shared_root, "merge-base", "--is-ancestor", main_commit, head_commit, check=False).returncode:
        raise BootstrapError("pinned main_commit is not an ancestor of the running skills-shared checkout")

    observed_tree = git_out(shared_root, "rev-parse", f"{main_commit}:{pin['owned_tree_path']}")
    if observed_tree != pin["owned_tree"]:
        raise BootstrapError("pinned owned_tree does not match the pinned main_commit's tree")

    candidate = pin["candidate_commit"]
    probe = run_git(shared_root, "cat-file", "-t", candidate, check=False)
    if probe.returncode or probe.stdout.strip() != "commit":
        raise BootstrapError("pinned candidate_commit is absent or not a commit")
    if run_git(shared_root, "merge-base", "--is-ancestor", main_commit, candidate, check=False).returncode:
        raise BootstrapError("pinned candidate_commit does not descend from the pinned main_commit")

    return head_commit, head_tree


