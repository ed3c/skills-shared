def artifact_records(consumer: Path, blocks: dict[Path, str], full_paths: list[Path]) -> list[dict[str, str]]:
    records: list[dict[str, str]] = []
    for relative in blocks:
        observed = observed_block(consumer / relative, GHPC_BEGIN, GHPC_END)
        records.append({
            "path": relative.as_posix(), "managed_block_sha256": sha256(observed.encode("utf-8")),
            "state": "MANAGED_BLOCK",
        })
    for relative in full_paths:
        path = consumer / relative
        if not path.is_file() or path.is_symlink():
            raise BootstrapError(f"generated artifact missing or non-regular: {relative}")
        records.append({"path": relative.as_posix(), "sha256": sha256(path.read_bytes()), "state": "GENERATED"})
    return sorted(records, key=lambda row: row["path"])


def build_ghpc_receipt(
    repository_id: str, repository_url_value: str, shared_commit: str, shared_tree: str,
    pin: dict[str, str], rollback: dict[str, str], artifacts: list[dict[str, str]],
    binding: dict[str, Any], profile_doc: dict[str, Any],
) -> dict[str, Any]:
    subject = {
        "consumer_repository": repository_id, "rollback": rollback,
        "shared_commit": shared_commit, "shared_tree": shared_tree, "artifacts": artifacts,
    }
    receipt: dict[str, Any] = {
        "schema": GHPC_RECEIPT_SCHEMA,
        "consumer": {
            "repository": repository_id, "generated_subject_sha256": sha256(canonical(subject)),
        },
        "shared_subject": {
            "repository": repository_url_value, "commit": shared_commit, "tree": shared_tree,
            "pinned_main_commit": pin["main_commit"],
            "pinned_owned_tree_path": pin["owned_tree_path"],
            "pinned_owned_tree": pin["owned_tree"],
            "pinned_candidate_commit": pin["candidate_commit"],
            "pinned_candidate_source_path": pin["candidate_source_path"],
        },
        "profile": {
            "id": profile_doc["profile"], "sha256": sha256(canonical(profile_doc)),
            "skills": list(profile_doc["skills"]),
        },
        "binding": {
            "path": GHPC_BINDING_REL.as_posix(), "semantic_sha256": sha256(canonical(binding)),
            "content_sha256": binding["content_sha256"],
        },
        "artifacts": artifacts,
        "evidence": expected_evidence(),
        "authority": {
            "automatic_merge": False, "automatic_conflict_resolution": False,
            "visibility_change": False, "credential_values": False,
            "provider_activation": False, "production_writeback": False,
        },
        "rollback": rollback,
        "decision_record_policy": "OBSERVATIONS_AND_DECISIONS_ONLY",
    }
    receipt["receipt_sha256"] = sha256(canonical(receipt))
    return receipt


def validate_ghpc_receipt_shape(receipt: dict[str, Any]) -> None:
    required = {
        "schema", "consumer", "shared_subject", "profile", "binding", "artifacts",
        "evidence", "authority", "rollback", "decision_record_policy", "receipt_sha256",
    }
    if set(receipt) != required or receipt.get("schema") != GHPC_RECEIPT_SCHEMA:
        raise BootstrapError("ghpc bootstrap receipt schema or fields drifted")
    reject_unsafe(receipt)
    unsigned = dict(receipt)
    claimed = unsigned.pop("receipt_sha256", None)
    if claimed != sha256(canonical(unsigned)):
        raise BootstrapError("ghpc bootstrap receipt self digest is stale")
    if receipt.get("decision_record_policy") != "OBSERVATIONS_AND_DECISIONS_ONLY":
        raise BootstrapError("ghpc bootstrap receipt attempted to persist private reasoning")
    authority = receipt.get("authority")
    if not isinstance(authority, dict) or not authority or any(v is not False for v in authority.values()):
        raise BootstrapError("ghpc bootstrap receipt widened automatic authority")
    if receipt.get("evidence") != expected_evidence():
        raise BootstrapError("ghpc bootstrap receipt promoted an unexercised or Human-owned lane")
    rollback = receipt.get("rollback")
    if not isinstance(rollback, dict) or set(rollback) != {"commit", "tree"}:
        raise BootstrapError("ghpc bootstrap receipt rollback subject is absent")
    if not HEX40.fullmatch(rollback["commit"]) or not HEX40.fullmatch(rollback["tree"]):
        raise BootstrapError("ghpc bootstrap receipt rollback identity is mutable")


def validate_ghpc_receipt(consumer: Path, expected: dict[str, Any]) -> None:
    path = consumer / GHPC_RECEIPT_REL
    if not path.is_file() or path.is_symlink():
        raise BootstrapError("ghpc bootstrap receipt missing or non-regular")
    observed = read_json(path)
    validate_ghpc_receipt_shape(observed)
    validate_rollback(consumer, observed["rollback"])
    if observed != expected:
        raise BootstrapError("ghpc bootstrap receipt is stale or substituted")
    for row in observed["artifacts"]:
        relative = row["path"]
        artifact = consumer / relative
        if not artifact.is_file() or artifact.is_symlink():
            raise BootstrapError(f"ghpc bootstrap receipt artifact is stale: {relative}")
        if row["state"] == "MANAGED_BLOCK":
            observed_digest = sha256(observed_block(artifact, GHPC_BEGIN, GHPC_END).encode("utf-8"))
        else:
            observed_digest = sha256(artifact.read_bytes())
        expected_digest = row.get("managed_block_sha256") or row.get("sha256")
        if observed_digest != expected_digest:
            raise BootstrapError(f"ghpc bootstrap receipt artifact is stale: {relative}")


def rollback_subject(consumer: Path, initial_commit: str, initial_tree: str) -> dict[str, str]:
    receipt_path = consumer / GHPC_RECEIPT_REL
    if not receipt_path.is_file():
        return {"commit": initial_commit, "tree": initial_tree}
    receipt = read_json(receipt_path)
    validate_ghpc_receipt_shape(receipt)
    validate_rollback(consumer, receipt["rollback"])
    return receipt["rollback"]


def preflight(consumer: Path) -> None:
    preflight_generated(consumer / GHPC_PROFILE_REL, {BINDING_DOC_SCHEMA})
    preflight_generated(consumer / GHPC_REQUIREMENTS_REL, {REQUIREMENTS_SCHEMA})
    preflight_generated(consumer / GHPC_BINDING_REL, {BINDING_SCHEMA})
    preflight_generated(consumer / GHPC_RECEIPT_REL, {GHPC_RECEIPT_SCHEMA})
    for relative in PORTFOLIO_STUB_RELS.values():
        preflight_generated(consumer / relative, {STUB_SCHEMA})
    preflight_generated(consumer / CODEX_CONFIG_REL, marker=CODEX_MARKER)
    for role in CODEX_ROLES:
        preflight_generated(consumer / codex_agent_rel(role), marker=CODEX_MARKER)


