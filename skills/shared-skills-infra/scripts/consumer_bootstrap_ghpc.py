def read_candidate_blob(shared_root: Path, candidate: str, relative: str) -> tuple[str, str]:
    result = subprocess.run(
        ["git", "-C", str(shared_root), "show", f"{candidate}:{relative}"],
        capture_output=True, check=False,
    )
    if result.returncode:
        raise BootstrapError(
            f"cannot read pinned candidate blob {candidate}:{relative}: "
            f"{result.stderr.decode('utf-8', 'replace').strip()}"
        )
    blob = git_out(shared_root, "rev-parse", f"{candidate}:{relative}")
    if not HEX40.fullmatch(blob):
        raise BootstrapError(f"invalid candidate blob identity for {relative}")
    return result.stdout.decode("utf-8"), blob


def codex_agent_texts(shared_root: Path, pin: dict[str, str]) -> dict[str, tuple[str, str, str]]:
    """role -> (generated .toml text, source template relative path, source git blob sha)."""
    result: dict[str, tuple[str, str, str]] = {}
    for role in CODEX_ROLES:
        relative = f"{pin['candidate_source_path']}/{role}.toml.template"
        body, blob = read_candidate_blob(shared_root, pin["candidate_commit"], relative)
        text = (
            f"{CODEX_MARKER}\n"
            f"# source: {pin['candidate_commit']}:{relative} (git_blob={blob})\n"
            "# ${MODEL_ID} and ${REASONING_EFFORT} are unresolved ALIAS_ONLY placeholders;\n"
            "# Human Admit must resolve them before this agent may be dispatched.\n\n"
            f"{body}"
        )
        result[role] = (text, relative, blob)
    return result


