def build_binding(
    repository_url_value: str, shared_commit: str, shared_tree: str, pin: dict[str, str],
    skills: list[str], shared_root: Path, requirements: dict[str, Any],
    codex_texts: dict[str, tuple[str, str, str]],
) -> dict[str, Any]:
    rows = [
        {
            "name": name, "content_sha256": content_sha256(shared_root / "skills" / name),
            "entrypoint": f"skills/{name}/SKILL.md",
        }
        for name in sorted(skills)
    ]
    codex_rows = [
        {"role": role, "template_path": codex_texts[role][1], "template_git_blob": codex_texts[role][2]}
        for role in CODEX_ROLES
    ]
    binding = {
        "schema": BINDING_SCHEMA,
        "binding": PROFILE_ID,
        "source": {"repository": repository_url_value, "commit": shared_commit, "tree": shared_tree},
        "pinned_subject": pin,
        "requirements_sha256": sha256(json_text(requirements).encode("utf-8")),
        "skills": rows,
        "codex_agents": codex_rows,
        "repo_owned": [],
        "surfaces": requirements["surfaces"],
    }
    binding["content_sha256"] = sha256(canonical(binding))
    return binding


def build_stub(kind: str, consumer_commit: str, consumer_tree: str) -> dict[str, Any]:
    doc: dict[str, Any] = {
        "schema": STUB_SCHEMA,
        "kind": kind,
        "epoch_subject": {"main_commit": consumer_commit, "tree": consumer_tree},
        "items": [],
    }
    doc["digest"] = sha256(canonical(doc))
    return doc


def verify_stub_static(path: Path, kind: str) -> None:
    if not path.is_file() or path.is_symlink():
        raise BootstrapError(f"portfolio stub missing or non-regular: {path}")
    doc = read_json(path)
    if doc.get("schema") != STUB_SCHEMA or doc.get("kind") != kind:
        raise BootstrapError(f"portfolio stub schema/kind drifted: {path}")
    if doc.get("items") != []:
        raise BootstrapError(f"portfolio stub is no longer an empty bootstrap stub: {path}")
    epoch = doc.get("epoch_subject")
    if (
        not isinstance(epoch, dict) or set(epoch) != {"main_commit", "tree"}
        or not HEX40.fullmatch(str(epoch.get("main_commit"))) or not HEX40.fullmatch(str(epoch.get("tree")))
    ):
        raise BootstrapError(f"portfolio stub epoch_subject is invalid: {path}")
    unsigned = dict(doc)
    claimed = unsigned.pop("digest", None)
    if claimed != sha256(canonical(unsigned)):
        raise BootstrapError(f"portfolio stub digest is stale: {path}")


