#!/usr/bin/env python3
"""Scaffold and verify the thin, atomic github-portfolio-control consumer profile.

Sibling to `consumer_bootstrap.py`, not a replacement for it: the default
profile keeps its own single fixed set of generated paths
(`.agents/control-plane/{source,profile,requirements}.json`,
`.agents/bindings/repository-control-plane.json`, ...) untouched. This module
adds a second, profile-namespaced bootstrap so a consumer can carry the
`github-portfolio-control` profile alongside (or instead of) the default one,
without either overwriting the other's generated paths.

Everything that is not specific to the github-portfolio-control profile is
imported from `consumer_bootstrap_common.py` (git/JSON/atomicity primitives)
and `consumer_bootstrap_routes.py` (managed-block merge/observe, parameterized
by this module's own begin/end markers so the default profile's blocks and
this profile's blocks can coexist in the same README.md/AGENTS.md without
collision) and `consumer_bootstrap_receipt.py` (rollback ancestry check).

Pin discipline: the profile pins three skills-shared subjects --
{main_commit, the exact tree of skills/github-portfolio-control at that
commit, and a not-yet-merged portfolio-core candidate commit the seven
Codex agent prompt templates are sourced from}. `validate_subject_pin`
refuses a substituted or non-ancestor pin before anything is written.
"""
