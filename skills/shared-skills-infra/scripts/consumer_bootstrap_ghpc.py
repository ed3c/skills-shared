def bootstrap_consumer_ghpc(
    *, consumer: Path, repository_id: str, profile_path: Path, apply: bool,
    shared_root: Path = SHARED_ROOT,
) -> None:
    if not REPOSITORY_ID.fullmatch(repository_id):
        raise BootstrapError("repository-id must be owner/name")
    consumer = consumer.resolve()
    initial_commit, initial_tree = ensure_git_worktree(consumer)

    profile_doc = ghpc_profile_document(profile_path)
    pin = profile_doc["subject_pin"]
    skills = list(profile_doc["skills"])
    shared_commit, shared_tree = validate_subject_pin(shared_root, pin)
    repository_url_value = repository_url(shared_root)

    blocks = ghpc_route_blocks(repository_id)
    requirements = build_requirements(skills)
    profile_binding = build_profile_binding(profile_doc)
    codex_texts = codex_agent_texts(shared_root, pin)
    config_text = codex_config_text(pin)
    full_paths = [
        GHPC_PROFILE_REL, GHPC_REQUIREMENTS_REL, GHPC_BINDING_REL,
        *PORTFOLIO_STUB_RELS.values(), CODEX_CONFIG_REL,
        *(codex_agent_rel(role) for role in CODEX_ROLES),
    ]

    preflight(consumer)
    reject_copied_skill_bodies(consumer, skills)

    if apply:
        rollback = rollback_subject(consumer, initial_commit, initial_tree)
        snapshot = capture(consumer, generated_paths())
        try:
            apply_routes(consumer, blocks)
            write_full(consumer, GHPC_PROFILE_REL, json_text(profile_binding))
            write_full(consumer, GHPC_REQUIREMENTS_REL, json_text(requirements))
            binding = build_binding(
                repository_url_value, shared_commit, shared_tree, pin, skills, shared_root,
                requirements, codex_texts,
            )
            write_full(consumer, GHPC_BINDING_REL, json_text(binding))

            stub_commit = git_out(consumer, "rev-parse", "HEAD")
            stub_tree = git_out(consumer, "rev-parse", "HEAD^{tree}")
            for kind, relative in PORTFOLIO_STUB_RELS.items():
                write_full(consumer, relative, json_text(build_stub(kind, stub_commit, stub_tree)))

            write_full(consumer, CODEX_CONFIG_REL, config_text)
            for role in CODEX_ROLES:
                write_full(consumer, codex_agent_rel(role), codex_texts[role][0])

            generated_texts = {
                p.as_posix(): (consumer / p).read_text(encoding="utf-8") for p in (*blocks, *full_paths)
            }
            assert_no_canonical_body_copied(shared_root, skills, generated_texts)

            artifacts = artifact_records(consumer, blocks, full_paths)
            receipt = build_ghpc_receipt(
                repository_id, repository_url_value, shared_commit, shared_tree, pin,
                rollback, artifacts, binding, profile_doc,
            )
            write_full(consumer, GHPC_RECEIPT_REL, json_text(receipt))
            validate_ghpc_receipt(consumer, receipt)
        except Exception:
            restore(consumer, snapshot)
            raise
    else:
        check_routes(consumer, blocks)
        check_full(consumer, GHPC_PROFILE_REL, json_text(profile_binding))
        check_full(consumer, GHPC_REQUIREMENTS_REL, json_text(requirements))
        binding = build_binding(
            repository_url_value, shared_commit, shared_tree, pin, skills, shared_root,
            requirements, codex_texts,
        )
        check_full(consumer, GHPC_BINDING_REL, json_text(binding))
        for kind, relative in PORTFOLIO_STUB_RELS.items():
            verify_stub_static(consumer / relative, kind)
        check_full(consumer, CODEX_CONFIG_REL, config_text)
        for role in CODEX_ROLES:
            check_full(consumer, codex_agent_rel(role), codex_texts[role][0])

        generated_texts = {
            p.as_posix(): (consumer / p).read_text(encoding="utf-8") for p in (*blocks, *full_paths)
        }
        assert_no_canonical_body_copied(shared_root, skills, generated_texts)

        existing = read_json(consumer / GHPC_RECEIPT_REL)
        validate_ghpc_receipt_shape(existing)
        validate_rollback(consumer, existing["rollback"])
        artifacts = artifact_records(consumer, blocks, full_paths)
        expected = build_ghpc_receipt(
            repository_id, repository_url_value, shared_commit, shared_tree, pin,
            existing["rollback"], artifacts, binding, profile_doc,
        )
        validate_ghpc_receipt(consumer, expected)

    print(
        "GHPC-BOOTSTRAP-GREEN "
        f"consumer={repository_id} shared={shared_commit[:12]} routes={len(blocks)} "
        f"mode={'apply' if apply else 'check'} hosted_evidence=NOT_EXERCISED "
        "merge=HUMAN_ADMIT_REQUIRED"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--consumer", required=True, type=Path)
    parser.add_argument("--repository-id", required=True)
    parser.add_argument("--profile", type=Path, default=PROFILE_SOURCE_GHPC)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--apply", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    profile = args.profile if args.profile.is_absolute() else SHARED_ROOT / args.profile
    try:
        bootstrap_consumer_ghpc(
            consumer=args.consumer, repository_id=args.repository_id,
            profile_path=profile, apply=args.apply,
        )
        return 0
    except BootstrapError as exc:
        print(f"GHPC-BOOTSTRAP-RED {exc}", file=sys.stderr)
        return 2
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        print(f"GHPC-BOOTSTRAP-INVALID {exc}", file=sys.stderr)
        return 64


if __name__ == "__main__":
    raise SystemExit(main())
