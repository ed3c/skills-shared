def content_sha256(path: Path) -> str:
    if not path.is_dir():
        raise BootstrapError(f"cannot digest missing Skill directory: {path}")
    sha = hashlib.sha256()
    for file in sorted(p for p in path.rglob("*") if p.is_file() and "__pycache__" not in p.parts):
        sha.update(file.relative_to(path).as_posix().encode("utf-8"))
        sha.update(b"\0")
        sha.update(file.read_bytes())
        sha.update(b"\0")
    return sha.hexdigest()


