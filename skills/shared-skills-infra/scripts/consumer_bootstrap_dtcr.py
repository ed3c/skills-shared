def apply_routes(consumer: Path, blocks: dict[Path, str]) -> None:
    for relative, block in blocks.items():
        path = consumer / relative
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(merge_block(current, block, relative, DTCR_BEGIN, DTCR_END), encoding="utf-8")


def check_routes(consumer: Path, blocks: dict[Path, str]) -> None:
    for relative, expected in blocks.items():
        observed = observed_block(consumer / relative, DTCR_BEGIN, DTCR_END)
        if observed != expected:
            raise BootstrapError(f"managed route block drifted: {relative}")


def write_full(consumer: Path, relative: Path, text: str) -> None:
    path = consumer / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def check_full(consumer: Path, relative: Path, expected_text: str) -> None:
    path = consumer / relative
    if not path.is_file() or path.is_symlink():
        raise BootstrapError(f"generated artifact missing or non-regular: {relative}")
    if path.read_text(encoding="utf-8") != expected_text:
        raise BootstrapError(f"generated artifact drifted: {relative}")


