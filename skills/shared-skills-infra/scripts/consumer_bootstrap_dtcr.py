def assert_no_canonical_body_copied(shared_root: Path, skills: list[str], texts: dict[str, str]) -> None:
    bodies: dict[str, str] = {}
    for name in skills:
        path = shared_root / "skills" / name / "SKILL.md"
        if path.is_file():
            bodies[f"skills/{name}/SKILL.md"] = path.read_text(encoding="utf-8")
    for relative in (
        f"{OWNED_TREE_PATH}/AGENTS.md", f"{OWNED_TREE_PATH}/README.md", PROMPT_CATALOGUE,
    ):
        path = shared_root / relative
        if path.is_file():
            bodies[relative] = path.read_text(encoding="utf-8")
    for generated_path, text in texts.items():
        for body_path, body_text in bodies.items():
            if body_text and body_text in text:
                raise BootstrapError(
                    f"generated {generated_path} embeds canonical body bytes copied from {body_path}"
                )


