def dtcr_profile_document(path: Path) -> dict[str, Any]:
    value = read_json(path)
    if value.get("schema") != PROFILE_SCHEMA:
        raise BootstrapError("unsupported control-plane profile")
    if value.get("profile") != PROFILE_ID:
        raise BootstrapError(f"profile is not the {PROFILE_ID} profile")
    skills = value.get("skills")
    if not isinstance(skills, list) or not skills or any(not isinstance(s, str) or not s for s in skills):
        raise BootstrapError("control-plane profile Skill closure is invalid")
    if PROFILE_ID not in skills:
        raise BootstrapError(f"control-plane profile does not select {PROFILE_ID}")
    authority = value.get("authority")
    if not isinstance(authority, dict) or not authority or any(v is not False for v in authority.values()):
        raise BootstrapError("control-plane profile widened automatic authority")
    validate_runtime_capabilities(value.get("runtime_capabilities"))
    pin = value.get("subject_pin")
    if not isinstance(pin, dict) or set(pin) != REQUIRED_PIN_KEYS:
        raise BootstrapError("control-plane profile is missing its subject pin")
    for key in ("main_commit", "owned_tree", "candidate_commit"):
        if not HEX40.fullmatch(str(pin[key])):
            raise BootstrapError(
                f"control-plane profile subject pin {key} is not an exact commit/tree SHA "
                "(a mutable ref such as main/latest is refused)"
            )
    if pin["candidate_commit"] != pin["main_commit"]:
        raise BootstrapError(
            "this profile declares no unmerged candidate source: candidate_commit must equal main_commit"
        )
    if pin["owned_tree_path"] != OWNED_TREE_PATH:
        raise BootstrapError(f"control-plane profile owned_tree_path must be {OWNED_TREE_PATH}")
    return value


def validate_runtime_capabilities(capabilities: Any) -> None:
    """`repository-control-plane-profile/v1` is `additionalProperties: false` and
    carries no field able to name an evidence path for a capability claim. A
    profile claiming an IMPLEMENTED installer or a PASSing service therefore
    makes an unprovable claim and is refused here rather than transcribed into a
    consumer authority. Broader language/build/provider capability claims have no
    field at all and stay NOT_IMPLEMENTED until a schema amendment is leased."""
    if not isinstance(capabilities, dict) or set(capabilities) != {"git_town", "forgejo"}:
        raise BootstrapError("control-plane profile runtime_capabilities drifted")
    git_town = capabilities["git_town"]
    forgejo = capabilities["forgejo"]
    if not isinstance(git_town, dict) or not isinstance(forgejo, dict):
        raise BootstrapError("control-plane profile runtime_capabilities entries are malformed")
    if git_town.get("installer_state") == "IMPLEMENTED":
        raise BootstrapError(
            "runtime_capabilities.git_town.installer_state=IMPLEMENTED has no evidence path in "
            "repository-control-plane-profile/v1; a supported-capability claim cannot be carried"
        )
    if forgejo.get("service_state") == "PASS":
        raise BootstrapError(
            "runtime_capabilities.forgejo.service_state=PASS has no evidence path in "
            "repository-control-plane-profile/v1; a supported-capability claim cannot be carried"
        )


def validate_subject_pin(shared_root: Path, pin: dict[str, str]) -> tuple[str, str]:
    """Prove the profile's declared subject pin is neither stale nor substituted,
    and return the running checkout's own (commit, tree)."""
    if git_out(shared_root, "status", "--porcelain", "--untracked-files=all"):
        raise BootstrapError("skills-shared source must be clean")
    head_commit = git_out(shared_root, "rev-parse", "HEAD")
    head_tree = git_out(shared_root, "rev-parse", "HEAD^{tree}")
    if not HEX40.fullmatch(head_commit) or not HEX40.fullmatch(head_tree):
        raise BootstrapError("invalid skills-shared commit/tree")

    main_commit = pin["main_commit"]
    probe = run_git(shared_root, "cat-file", "-t", main_commit, check=False)
    if probe.returncode or probe.stdout.strip() != "commit":
        raise BootstrapError("pinned main_commit is absent from this checkout's object database")
    if run_git(shared_root, "merge-base", "--is-ancestor", main_commit, head_commit, check=False).returncode:
        raise BootstrapError("pinned main_commit is not an ancestor of the running skills-shared checkout")

    observed_tree = git_out(shared_root, "rev-parse", f"{main_commit}:{pin['owned_tree_path']}")
    if observed_tree != pin["owned_tree"]:
        raise BootstrapError("pinned owned_tree does not match the pinned main_commit's tree")
    return head_commit, head_tree


def prompt_catalogue_pin(shared_root: Path, main_commit: str) -> dict[str, str]:
    """Pin the canonical prompt catalogue by exact blob -- the consumer receives
    this pointer, never these bytes."""
    relative = f"{main_commit}:{PROMPT_CATALOGUE}"
    result = subprocess.run(
        ["git", "-C", str(shared_root), "show", relative], capture_output=True, check=False
    )
    if result.returncode:
        raise BootstrapError(
            f"pinned prompt catalogue is absent: {relative}: "
            f"{result.stderr.decode('utf-8', 'replace').strip()}"
        )
    blob = git_out(shared_root, "rev-parse", relative)
    if not HEX40.fullmatch(blob):
        raise BootstrapError("invalid prompt catalogue blob identity")
    return {"path": PROMPT_CATALOGUE, "git_blob": blob, "sha256": sha256(result.stdout)}


