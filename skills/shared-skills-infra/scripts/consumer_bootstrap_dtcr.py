# EXISTING_GOVERNANCE_DISCOVERED -> COMPATIBILITY_AND_COLLISION_CHECKED
# ---------------------------------------------------------------------------


def preflight_collisions(consumer: Path) -> None:
    """Enumerate the consumer's managed marker pairs, generated JSON authorities
    and workflow files BEFORE any write. Each case has its own exit code."""
    for relative in DTCR_DOC_ROUTES:
        path = consumer / relative
        if not path.is_file() or path.is_symlink():
            continue
        for name in sorted({m.group("name") for m in MARKER_PAIR.finditer(path.read_text(encoding="utf-8"))}):
            if name == DTCR_MARKER_NAME:
                continue
            if name in DTCR_MARKER_NAME or DTCR_MARKER_NAME in name:
                raise CollisionError(
                    EXIT_COLLISION_MARKER,
                    f"existing managed marker pair collides with this profile's pair in {relative}: "
                    f"<!-- BEGIN {name} -->",
                )

    for relative, schemas in (
        (DTCR_PROFILE_REL, {BINDING_DOC_SCHEMA}),
        (DTCR_REQUIREMENTS_REL, {REQUIREMENTS_SCHEMA}),
        (DTCR_BINDING_REL, {BINDING_SCHEMA}),
        (DTCR_RECEIPT_REL, {DTCR_RECEIPT_SCHEMA}),
    ):
        try:
            preflight_generated(consumer / relative, schemas)
        except BootstrapError as exc:
            raise CollisionError(EXIT_COLLISION_AUTHORITY, str(exc)) from exc

    workflows = consumer / ".github/workflows"
    if workflows.is_dir():
        for path in sorted(workflows.iterdir()):
            if not path.is_file() or path.is_symlink():
                continue
            if DTCR_WORKFLOW_MARKER in path.read_text(encoding="utf-8", errors="replace"):
                raise CollisionError(
                    EXIT_COLLISION_WORKFLOW,
                    f"workflow claims this profile's generated marker but this profile generates no "
                    f"workflow: {path.relative_to(consumer).as_posix()}",
                )


def assert_single_owner(consumer: Path) -> None:
    """Refuse a second task-state owner under this profile id."""
    path = consumer / DTCR_BINDING_REL
    if not path.is_file() or path.is_symlink():
        return
    observed = read_json(path).get("binding")
    if observed != PROFILE_ID:
        raise BootstrapError(
            f"duplicate task-state owner: {DTCR_BINDING_REL.as_posix()} is owned by {observed!r}, "
            f"not {PROFILE_ID!r}"
        )


# ---------------------------------------------------------------------------
# orchestration
# ---------------------------------------------------------------------------


def bootstrap_consumer_dtcr(
    *, consumer: Path, repository_id: str, profile_path: Path, apply: bool,
    shared_root: Path = SHARED_ROOT,
) -> None:
    if not REPOSITORY_ID.fullmatch(repository_id):
        raise BootstrapError("repository-id must be owner/name")
    consumer = consumer.resolve()
    initial_commit, initial_tree = ensure_git_worktree(consumer)

    assert_generated_disjoint()
    profile_doc = dtcr_profile_document(profile_path)
    pin = profile_doc["subject_pin"]
    skills = list(profile_doc["skills"])
    shared_commit, shared_tree = validate_subject_pin(shared_root, pin)
    catalogue = prompt_catalogue_pin(shared_root, pin["main_commit"])
    repository_url_value = repository_url(shared_root)

    blocks = dtcr_route_blocks(repository_id, pin, catalogue)
    requirements = build_requirements(skills)
    profile_binding = build_profile_binding(profile_doc)
    fulls = full_paths()

    preflight_collisions(consumer)
    assert_single_owner(consumer)
    reject_copied_skill_bodies(consumer, skills)

    if apply:
        rollback = rollback_subject(consumer, initial_commit, initial_tree)
        snapshot = capture(consumer, generated_paths())
        try:
            apply_routes(consumer, blocks)
            write_full(consumer, DTCR_PROFILE_REL, json_text(profile_binding))
            write_full(consumer, DTCR_REQUIREMENTS_REL, json_text(requirements))
            binding = build_binding(
                repository_url_value, shared_commit, shared_tree, pin, skills, shared_root,
                requirements, catalogue,
            )
            write_full(consumer, DTCR_BINDING_REL, json_text(binding))

            generated_texts = {
                p.as_posix(): (consumer / p).read_text(encoding="utf-8") for p in (*blocks, *fulls)
            }
            assert_no_canonical_body_copied(shared_root, skills, generated_texts)

            artifacts = artifact_records(consumer, blocks, fulls)
            receipt = build_dtcr_receipt(
                repository_id, repository_url_value, shared_commit, shared_tree, pin, catalogue,
                rollback, artifacts, binding, profile_doc,
            )
            write_full(consumer, DTCR_RECEIPT_REL, json_text(receipt))
            validate_dtcr_receipt(consumer, receipt)
        except Exception:
            restore(consumer, snapshot)
            raise
    else:
        check_routes(consumer, blocks)
        check_full(consumer, DTCR_PROFILE_REL, json_text(profile_binding))
        check_full(consumer, DTCR_REQUIREMENTS_REL, json_text(requirements))
        binding = build_binding(
            repository_url_value, shared_commit, shared_tree, pin, skills, shared_root,
            requirements, catalogue,
        )
        check_full(consumer, DTCR_BINDING_REL, json_text(binding))

        generated_texts = {
            p.as_posix(): (consumer / p).read_text(encoding="utf-8") for p in (*blocks, *fulls)
        }
        assert_no_canonical_body_copied(shared_root, skills, generated_texts)

        existing = read_json(consumer / DTCR_RECEIPT_REL)
        validate_dtcr_receipt_shape(existing)
        validate_rollback(consumer, existing["rollback"])
        artifacts = artifact_records(consumer, blocks, fulls)
        expected = build_dtcr_receipt(
            repository_id, repository_url_value, shared_commit, shared_tree, pin, catalogue,
            existing["rollback"], artifacts, binding, profile_doc,
        )
        validate_dtcr_receipt(consumer, expected)

    print(
        "DTCR-BOOTSTRAP-GREEN "
        f"consumer={repository_id} shared={shared_commit[:12]} routes={len(blocks)} "
        f"mode={'apply' if apply else 'check'} runtime=NOT_EXERCISED registry_admission=ABSENT "
        "hosted_workflow=NOT_EXERCISED real_consumer=NOT_SELECTED completion_dependency_525=OPEN "
        "merge=HUMAN_ADMIT_REQUIRED terminal=NOT_EMITTED"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--consumer", required=True, type=Path)
    parser.add_argument("--repository-id", required=True)
    parser.add_argument("--profile", type=Path, default=PROFILE_SOURCE_DTCR)
    parser.add_argument("--shared-root", type=Path, default=SHARED_ROOT)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--apply", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    shared_root = args.shared_root.resolve()
    profile = args.profile if args.profile.is_absolute() else shared_root / args.profile
    try:
        bootstrap_consumer_dtcr(
            consumer=args.consumer, repository_id=args.repository_id,
            profile_path=profile, apply=args.apply, shared_root=shared_root,
        )
        return 0
    except CollisionError as exc:
        print(f"DTCR-BOOTSTRAP-COLLISION {exc}", file=sys.stderr)
        return exc.code
    except BootstrapError as exc:
        print(f"DTCR-BOOTSTRAP-RED {exc}", file=sys.stderr)
        return 2
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        print(f"DTCR-BOOTSTRAP-INVALID {exc}", file=sys.stderr)
        return 64


if __name__ == "__main__":
    raise SystemExit(main())
