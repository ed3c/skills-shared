#!/usr/bin/env python3
"""Scaffold and verify the thin, atomic dual-track-code-review-loop consumer profile.

Third sibling of `consumer_bootstrap.py` (default profile) and
`consumer_bootstrap_ghpc.py` (github-portfolio-control), built to the same
shape and for the same mechanical reason: `consumer_bootstrap.py --profile`
routes through `repository_control_plane.validate_profile`, which hard-fails on
`profile["skills"] != REQUIRED_ORDER` -- a hardcoded exact six-name, exact-order
list. Any profile selecting `dual-track-code-review-loop` is rejected there
before a byte is written, so a profile-namespaced sibling module is the only
live path. This module therefore never imports `repository_control_plane`; it
imports only the shared primitives (`consumer_bootstrap_common`,
`consumer_bootstrap_routes`, `consumer_bootstrap_receipt`).

Generated consumer surface -- exactly one managed block plus four authorities:

    AGENTS.md                                                          (managed block)
    .agents/control-plane/profiles/dual-track-code-review-loop.json
    .agents/control-plane/requirements/dual-track-code-review-loop.json
    .agents/bindings/dual-track-code-review-loop.json
    .agents/control-plane/bootstrap-receipt.dual-track-code-review-loop.json

The managed block ROUTES to the canonical prompt catalogue
(`skills/dual-track-code-review-loop/references/prompts/README.md`, pinned by
exact commit and blob) -- no prompt body, session-dispatch, handoff or receipt
body is copied into the consumer, and `.agents/prompt-packets/**`,
`.agents/session-dispatch/**`, `.agents/handoffs/**` and `.agents/receipts/**`
are deliberately out of scope: they have no generator, schema, fixture or
precedent anywhere in this repository, and a consumer's own receipts stay
consumer-owned.

Pin discipline: `subject_pin` is all-or-nothing per the profile schema, and this
profile declares NO unmerged candidate source, so `candidate_commit` MUST equal
`main_commit`. Mutable refs (`main`, `latest`, a branch name) are refused by the
`HEX40` fullmatch before anything is written.

What this module deliberately does NOT do: it never writes a `.github/workflows`
file, never claims a runtime, registry, hosted-workflow or provider lane, and
never promotes a green bootstrap into any of them. Because it targets no
workflow path at all, its workflow collision check is the contrapositive of the
default profile's: any consumer workflow carrying THIS profile's generated
marker is an impostor or a stale artifact of a substituted generator, and the
run fails closed on it.
"""
